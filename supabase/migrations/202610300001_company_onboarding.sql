-- Business accounts are no longer open to sign-up: the admin gathers each company in the panel and creates its account.
-- The company receives a temporary password by email and must replace it on its first visit.

alter table public.tbl_usuarios
  add column if not exists debe_cambiar_clave boolean not null default false,
  add column if not exists clave_temporal_vence timestamptz;

-- What the admin collects about a company, from the first contact until it has an account.
create table if not exists public.company_prospects (
  id bigint generated by default as identity primary key,
  contact_name text not null default '' check (char_length(contact_name) <= 60),
  contact_email text not null default '' check (char_length(contact_email) <= 160),
  contact_phone text check (char_length(contact_phone) <= 30),
  business_name text not null check (char_length(business_name) between 2 and 100),
  kind text not null check (kind in ('radio_taxi','venue','tour','other')),
  region text not null check (region in ('AP','TA','AN','AT','CO','VS','RM','LI','ML','NB','BI','AR','LR','LL','AI','MA')),
  comuna text check (char_length(comuna) <= 80),
  address text check (char_length(address) <= 200),
  whatsapp text check (char_length(whatsapp) <= 30),
  url text check (char_length(url) <= 300),
  languages text[] not null default '{}',
  description text check (char_length(description) <= 600),
  -- The services it will offer, as typed in the panel. They become rows of services when the account is created.
  services jsonb not null default '[]'::jsonb check (jsonb_typeof(services) = 'array'),
  notes text check (char_length(notes) <= 1000),
  estado text not null default 'prospecto' check (estado in ('prospecto','invitada','activa','descartada')),
  application_id bigint references public.business_applications (id) on delete set null,
  partner_id bigint references public.partners (id) on delete set null,
  user_id uuid references auth.users (id) on delete set null,
  invited_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.company_prospects enable row level security;
revoke all on public.company_prospects from anon, authenticated;
grant select, insert, update, delete on public.company_prospects to service_role;
grant usage, select on sequence public.company_prospects_id_seq to service_role;

comment on table public.company_prospects is 'Empresas que el equipo contacta. Solo el servidor las lee y escribe; el panel admin crea su cuenta desde aquí.';
comment on column public.tbl_usuarios.debe_cambiar_clave is 'La empresa entró con una clave temporal y debe crear la suya antes de usar su panel.';

-- Sign-up only creates travellers: what a client sends can no longer ask for a business account. The API turns an
-- account into a company afterwards, when the admin creates it (invite-company in api/_routes/admin.ts).
create or replace function public.handle_new_app_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  nombre text := left(btrim(coalesce(meta->>'first_name', '')), 60);
  pais text := left(btrim(coalesce(meta->>'country', '')), 80);
  idioma text := meta->>'preferred_language';
  moneda text := meta->>'preferred_currency';
begin
  insert into public.tbl_usuarios (id, nombre, pais, idioma, moneda)
  values (
    new.id,
    case when char_length(nombre) >= 2 then nombre else 'Viajero' end,
    case when char_length(pais) >= 2 then pais else 'Sin informar' end,
    case when idioma in ('es','en','pt','fr') then idioma else 'es' end,
    case when moneda in ('CLP','ARS','BRL','USD','EUR','PEN','COP','UYU','GBP','CAD','MXN','AUD') then moneda else 'CLP' end
  )
  on conflict (id) do nothing;
  return new;
end;
$$;
