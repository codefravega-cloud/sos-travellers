-- Services that a business offers to travellers (a tour, a transfer, a stay…), and the approval of business accounts.
-- Three kinds of account see different things: the admin manages everything, a traveller (cliente) sees the
-- published services, and a business (empresa) edits only its own. Every service waits for the admin before it shows.

-- A business account that signs up by itself waits for the admin; one the admin turns into empresa is approved.
alter table public.tbl_usuarios
  add column if not exists aprobacion text not null default 'aprobada' check (aprobacion in ('pendiente','aprobada','rechazada')),
  add column if not exists aprobacion_motivo text check (char_length(aprobacion_motivo) <= 500);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  partner_id bigint not null references public.partners (id) on delete cascade,
  category text not null check (category in ('tour','transfer','stay','food','experience','guide','other')),
  title text not null check (char_length(title) between 3 and 80),
  description text not null check (char_length(description) between 10 and 600),
  -- Pesos; price_from means "desde $…". Null when the price is agreed with the traveller.
  price_clp integer check (price_clp between 0 and 100000000),
  price_from boolean not null default false,
  duration text check (char_length(duration) <= 40),
  languages text[] not null default '{}',
  whatsapp text check (char_length(whatsapp) <= 30),
  phone text check (char_length(phone) <= 30),
  booking_url text check (char_length(booking_url) <= 300),
  -- Paths in the business-photos bucket (services/<id>/<uuid>.<ext>), at most 3. They are approved with the service.
  photos jsonb not null default '[]'::jsonb check (jsonb_typeof(photos) = 'array'),
  -- Every new or edited service goes back to pending until the admin publishes it; review_note tells the business why
  -- it was rejected.
  status text not null default 'pending' check (status in ('pending','published','rejected')),
  review_note text check (char_length(review_note) <= 300),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists services_partner_idx on public.services (partner_id);
create index if not exists services_published_idx on public.services (category) where status = 'published';

alter table public.services enable row level security;
grant select, insert, update, delete on public.services to service_role;
grant usage, select on sequence public.services_id_seq to service_role;

create trigger services_auditoria after insert or update or delete on public.services
  for each row execute function public.registrar_cambio();

-- Sign-up: a business account also gets its business (a draft row of partners) from the data sent at sign-up, and
-- waits for the admin. Only 'cliente' or 'empresa' can be asked for; admin is never granted here.
create or replace function public.handle_new_app_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  nombre text := left(btrim(coalesce(meta->>'first_name', '')), 60);
  pais text := left(btrim(coalesce(meta->>'country', '')), 80);
  idioma text := meta->>'preferred_language';
  moneda text := meta->>'preferred_currency';
  empresa boolean := meta->>'tipo_cuenta' = 'empresa';
  negocio text := left(btrim(coalesce(meta->>'business_name', '')), 100);
  region text := meta->>'business_region';
  tipo text := meta->>'business_kind';
begin
  insert into public.tbl_usuarios (id, nombre, pais, idioma, moneda, tipo_cuenta, aprobacion)
  values (
    new.id,
    case when char_length(nombre) >= 2 then nombre else 'Viajero' end,
    case when char_length(pais) >= 2 then pais else 'Sin informar' end,
    case when idioma in ('es','en','pt','fr') then idioma else 'es' end,
    case when moneda in ('CLP','ARS','BRL','USD','EUR','PEN','COP','UYU','GBP','CAD','MXN','AUD') then moneda else 'CLP' end,
    case when empresa then 'empresa' else 'cliente' end,
    case when empresa then 'pendiente' else 'aprobada' end
  )
  on conflict (id) do nothing;

  if empresa then
    insert into public.partners (kind, name, region, owner_id, status)
    values (
      case when tipo in ('radio_taxi','venue','tour','other') then tipo else 'other' end,
      case when char_length(negocio) >= 2 then negocio else 'Mi empresa' end,
      case when region in ('AP','TA','AN','AT','CO','VS','RM','LI','ML','NB','BI','AR','LR','LL','AI','MA') then region else 'RM' end,
      new.id,
      'draft'
    );
  end if;
  return new;
end;
$$;

comment on table public.services is 'Servicios que ofrece cada negocio a los viajeros. Solo se muestran con status = published y el negocio publicado.';
comment on column public.tbl_usuarios.aprobacion is 'Cuentas empresa: pendiente hasta que el admin la aprueba. Las demás cuentas quedan aprobadas.';

notify pgrst, 'reload schema';
